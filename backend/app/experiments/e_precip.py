C = "precip"


def pp(id, title, level, a, a_ml, b, b_ml, solid, color, theory, eq, extra_steps=(), extra_expect=(), tags=(),
       summary=None):
    return Exp(id, title, C, level, summary or f"Zmieszaj roztwory i obserwuj wytrącanie osadu {solid}.",
               [V("t1", "test_tube", None, (a, a_ml))],
               [S("Dodaj roztwór odczynnika strącającego.", add("t1", b, b_ml), stir("t1"), wait=3), *extra_steps],
               [("event", f"({solid})"), ("event", color), *extra_expect],
               theory=theory, equations=eq, tags=("strącanie",) + tuple(tags))


