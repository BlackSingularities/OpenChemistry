C = "electro"


def elec(id, title, level, summary, fill, expect, theory, eq, electrode="C", wait=150, extra_tests=(), tags=()):
    return Exp(id, title, C, level, summary, [V("u", "utube", None, *fill)],
               [S("Włącz zasilacz (12 V).", power("u", True, electrode), wait=wait),
                S("Zbadaj produkty przy elektrodach.", *[test("u", t) for t in extra_tests], wait=1)
                if extra_tests else S("Wyłącz zasilacz.", power("u", False), wait=1)],
               expect, theory=theory, equations=eq, tags=("elektroliza",) + tuple(tags))


